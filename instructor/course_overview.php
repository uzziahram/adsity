    $stmtUser = $pdo->prepare("SELECT id, full_name, email FROM users WHERE id = :id AND role_id = 2 LIMIT 1");
    $stmtUser->execute([':id' => $instructorId]);
    $instructor = $stmtUser->fetch();

    if (!$instructor) {
        header('Location: ../login.php?status=error&message=' . urlencode('Instructor account not found.'));
        exit;
    }

    // 2. Fetch Course Details (Must belong to this instructor)
    $stmtCourse = $pdo->prepare("SELECT * FROM courses WHERE id = :cid AND instructor_id = :iid LIMIT 1");
    $stmtCourse->execute([':cid' => $courseId, ':iid' => $instructorId]);
    $course = $stmtCourse->fetch();

    if (!$course) {
        header('Location: dashboard.php?status=error&message=' . urlencode('Course not found or you do not have permission to view it.'));
        exit;
    }

    // 3. Fetch Lessons for this Course
    $stmtLessons = $pdo->prepare("SELECT * FROM lessons WHERE course_id = :cid ORDER BY lesson_number ASC");
    $stmtLessons->execute([':cid' => $courseId]);
    $lessons = $stmtLessons->fetchAll();
    $totalLessonsCount = count($lessons) > 0 ? count($lessons) : (int)($course['total_lessons'] ?? 1);

    // 4. Fetch Course Performance Metrics (No average progress per instructor preference)
    // Enrolled students count
    $stmtEnrolled = $pdo->prepare("SELECT COUNT(DISTINCT user_id) FROM enrollments WHERE course_id = :cid");
    $stmtEnrolled->execute([':cid' => $courseId]);
    $totalEnrolled = (int)$stmtEnrolled->fetchColumn();

    // Certificates awarded count
