                                FROM ad_activity_logs 
                                WHERE course_id = :cid AND instructor_id = :iid");
    $stmtAdRev->execute([':cid' => $courseId, ':iid' => $instructorId]);
    $adData = $stmtAdRev->fetch();
    $totalAdRevenue = (float)($adData['total_revenue'] ?? 0);
    $totalAdViews   = (int)($adData['total_views'] ?? 0);

    // 5. Fetch Enrolled Students & Their Progress Roster
    $sqlStudents = "SELECT 
                        u.id AS student_id,
                        u.full_name AS student_name,
                        u.email AS student_email,
                        e.progress_percent,
                        e.status AS enrollment_status,
                        e.enrolled_at,
                        e.completed_at,
                        COUNT(DISTINCT lc.lesson_id) AS completed_lessons_count,
                        cert.certificate_code,
                        cert.issued_at AS cert_issued_at,
                        sub.id AS submission_id,
                        sub.submission_type,
                        sub.submission_value,
                        sub.notes AS submission_notes,
                        sub.instructor_feedback,
                        sub.status AS submission_status,
                        sub.submitted_at
                    FROM enrollments e
                    JOIN users u ON e.user_id = u.id
                    LEFT JOIN lesson_completions lc ON lc.user_id = u.id AND lc.course_id = e.course_id
                    LEFT JOIN certificates cert ON cert.user_id = u.id AND cert.course_id = e.course_id
                    LEFT JOIN (
                        SELECT cs1.*
                        FROM course_submissions cs1
                        INNER JOIN (
                            SELECT MAX(id) AS max_id
                            FROM course_submissions
                            GROUP BY user_id, course_id
                        ) cs2 ON cs1.id = cs2.max_id
                    ) sub ON sub.user_id = u.id AND sub.course_id = e.course_id
                    WHERE e.course_id = :cid
                    GROUP BY u.id, e.id
                    ORDER BY e.enrolled_at DESC";
    $stmtStudents = $pdo->prepare($sqlStudents);
    $stmtStudents->execute([':cid' => $courseId]);
    $students = $stmtStudents->fetchAll();

    // 6. Lesson completion stats (how many students finished each lesson)
    $lessonCompletionStats = [];
    if (!empty($lessons)) {
        $stmtLessonStats = $pdo->prepare("SELECT lesson_id, COUNT(DISTINCT user_id) AS completions_count 
                                          FROM lesson_completions 
                                          WHERE course_id = :cid 
                                          GROUP BY lesson_id");
        $stmtLessonStats->execute([':cid' => $courseId]);
        while ($row = $stmtLessonStats->fetch()) {
            $lessonCompletionStats[(int)$row['lesson_id']] = (int)$row['completions_count'];
        }
    }

    // 7. Total Courses count (for sidebar badge)
    $stmtCountCourses = $pdo->prepare("SELECT COUNT(*) FROM courses WHERE instructor_id = :iid");
    $stmtCountCourses->execute([':iid' => $instructorId]);
    $totalCoursesCount = (int)$stmtCountCourses->fetchColumn();

    // 8. Total Submissions count (for sidebar badge)
    $stmtCountSubs = $pdo->prepare("SELECT COUNT(sub.id) FROM course_submissions sub JOIN courses c ON sub.course_id = c.id WHERE c.instructor_id = :iid");
    $stmtCountSubs->execute([':iid' => $instructorId]);
    $totalSubmissionsCount = (int)$stmtCountSubs->fetchColumn();

    // 9. Wallet total earned (for sidebar badge)
    $stmtWallet = $pdo->prepare("SELECT total_earned FROM instructor_wallets WHERE instructor_id = :iid LIMIT 1");
    $stmtWallet->execute([':iid' => $instructorId]);
    $totalEarnedWallet = (float)($stmtWallet->fetchColumn() ?: 0);

} catch (PDOException $e) {
    error_log('Instructor course overview error: ' . $e->getMessage());
